		id: row.id,
		category: row.category,
		subcategory: row.sub ?? "",
		nameHi: row.nameHi,
		nameEn: row.nameEn,
		price: row.price,
		icon: row.icon,
		image: row.image,
		pieces: row.pieces ?? 1,
		days: row.days ?? 2,
		featured: row.featured ?? false,
